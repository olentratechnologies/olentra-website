import { afterAll, beforeAll, expect, test } from "bun:test";
import { createHash, randomUUID } from "node:crypto";
import { internshipTestMongoUri } from "./config";
import { connectInternDatabase, createInternshipDomain, DomainError, type Principal } from "./domain";

const uri = internshipTestMongoUri();
if (!uri) throw new Error("Set INTERNSHIP_TEST_MONGODB_URI (or deprecated INTERN_TEST_MONGODB_URI) for the isolated Atlas integration test.");
const prefix = `test_intern_life_${randomUUID().replaceAll("-", "")}_`;
let connection: Awaited<ReturnType<typeof connectInternDatabase>>;
let domain: ReturnType<typeof createInternshipDomain>;
const staff: Principal = { id: "staff-test", role: "company", staffRole: "admin", name: "Test Staff", email: "staff@example.test", applicationId: null, sessionVersion: 1 };
let sequence = 0;
const key = () => `test-lifecycle-${String(++sequence).padStart(10, "0")}`;
const call = (method: string, params: Record<string, any>, actor: Principal | null = staff, requestKey = key()) => domain.execute(method, params, actor, requestKey);

beforeAll(async () => { connection = await connectInternDatabase(uri!); domain = createInternshipDomain({ ...connection, prefix }); await domain.initialize(); await domain.collection("accounts").insertOne({ _id: staff.id, role: staff.role, staffRole: "admin", name: staff.name, email: staff.email, sessionVersion: 1 }); }, 20000);
afterAll(async () => { if (!connection) return; for (const { name } of await connection.db.listCollections({}, { nameOnly: true }).toArray()) if (name.startsWith(prefix)) await connection.db.collection(name).drop(); await connection.client.close(); }, 30000);

test("application through approved work and one certificate, with ownership and replay protections", async () => {
  await call("program.configure", { programId: "software-engineer", fee: 0, stipend: 100, enabled: true });
  await call("settings.update", { patch: { programEnabled: true, durationSpec:{quantity:1,unit:"months"} } });
  const fileToken = "test-token";
  await domain.collection("files").insertOne({ _id: "resume", kind: "resume", status: "ready", accessTokenHash: createHash("sha256").update(fileToken).digest("hex") });
  await call("application.submit", { name: "Test Intern", email: "life@example.test", linkedin: "https://www.linkedin.com/in/test-candidate", programId: "software-engineer", schedule: "part_time", resumeAttachmentId: "resume", resumeAccessToken: fileToken }, null);
  const application = { id: String((await domain.collection("applications").findOne({ email: "life@example.test" }))!._id) };
  const statusEmails: string[] = [], interviewEmails: string[] = [];
  domain.setHooks({
    sendApplicantStatus: async notice => {
      const persisted = await domain.collection("applications").findOne({ email: notice.to });
      expect(persisted).toBeTruthy();
      if (notice.status === "shortlisted") expect(persisted?.status).toBe("Shortlisted");
      if (notice.status === "offer") expect(await domain.collection("offers").findOne({ applicationId: persisted?._id, status: "Sent" })).toBeTruthy();
      if (notice.status === "onboarding") expect(await domain.collection("onboarding").findOne({ applicationId: persisted?._id, status: "Approved" })).toBeTruthy();
      if (notice.status === "certificate") expect(await domain.collection("certificates").findOne({ applicationId: persisted?._id, certificateNumber: notice.certificateNumber })).toBeTruthy();
      statusEmails.push(notice.status);
    },
    sendInterviewScheduled: async notice => {
      expect(await domain.collection("interviews").findOne({ meetingUrl: notice.meetingUrl, scheduledAt: notice.scheduledAt })).toBeTruthy();
      interviewEmails.push(notice.meetingUrl);
    },
  });
  await expect(call("offer.send", { applicationId: application.id, startOn: "2026-11-01", endOn: "2026-12-01", stipend: 50 })).rejects.toBeInstanceOf(DomainError);
  await call("application.update", { id: application.id, status: "Shortlisted", expectedVersion: 1 });
  expect(statusEmails).not.toContain("shortlisted");
  await domain.processOutbox();
  expect(statusEmails).toContain("shortlisted");
  const scheduledAt = new Date(Date.now() + 60 * 60 * 1000).toISOString();
  const interviewKey = key();
  const interview = await call("interview.schedule", { applicationId: application.id, scheduledAt, meetingUrl: "https://meet.example.test/interview" }, staff, interviewKey);
  await call("interview.schedule", { applicationId: application.id, scheduledAt, meetingUrl: "https://meet.example.test/interview" }, staff, interviewKey);
  expect(interviewEmails).toHaveLength(0);
  await domain.processOutbox();
  expect(interview.applicationId).toBe(application.id);
  expect(interviewEmails).toEqual(["https://meet.example.test/interview"]);
  const rescheduled = await call("interview.schedule", { applicationId: application.id, scheduledAt: new Date(Date.now() + 2 * 60 * 60 * 1000).toISOString(), meetingUrl: "https://meet.example.test/updated" });
  await domain.processOutbox();
  expect(rescheduled.id).toBe(interview.id);
  expect(await domain.collection("interviews").countDocuments({ applicationId: application.id })).toBe(1);
  expect(interviewEmails).toEqual(["https://meet.example.test/interview", "https://meet.example.test/updated"]);
  await call("application.update", { id: application.id, status: "Selected", expectedVersion: 2 });
  const intern: Principal = await domain.autoProvisionAccount(application.id, "life@example.test");
  const other: Principal = { ...intern, id: "other", applicationId: "other" };
  await domain.processOutbox();
  const withNote = await call("application.update", { id: application.id, expectedVersion: 3, patch: { notes: [{ text: "Private staff note", author: "forged" }] } });
  expect(withNote.notes[0].author).toBe(staff.name);
  expect((await call("application.get", { id: application.id }, intern)).notes).toBeUndefined();
  await expect(call("offer.send", { applicationId: application.id, startOn: "2026-02-31", endOn: "2026-12-01", stipend: 50 })).rejects.toBeInstanceOf(DomainError);
  const preview = await call("offer.preview", {applicationId:application.id,startOn:"2030-11-24"});
  const offerTerms = { ...preview, stipend: 50 };
  const offerKey = key();
  await call("offer.send", offerTerms, staff, offerKey);
  await call("offer.send", offerTerms, staff, offerKey);
  expect(statusEmails).not.toContain("offer");
  await domain.processOutbox();
  expect(statusEmails).toContain("offer");
  expect(statusEmails.filter(status => status === "offer")).toHaveLength(1);
  await expect(call("offer.accept", { applicationId: application.id, version:1 }, other)).rejects.toBeInstanceOf(DomainError);
  await call("offer.accept", { applicationId: application.id, version:1 }, intern);
  const acceptedActivity = await domain.collection("activity").findOne({ title: "Internship offer accepted", applicationId: application.id });
  expect(acceptedActivity?.detail).toContain("Test Intern accepted the Software Engineer Intern offer");
  expect(acceptedActivity?.detail).not.toBe(acceptedActivity?.title);
  await expect(call("onboarding.approve", { applicationId: application.id })).rejects.toBeInstanceOf(DomainError);
  await call("onboarding.save", { applicationId: application.id, details: { phone: "123456", college: "Test College", location: "Test City", skills: ["React", "MongoDB"], acknowledged: true } }, intern);
  await call("onboarding.submit", { applicationId: application.id }, intern);
  const approvalKey = key();
  const active = await call("onboarding.approve", { applicationId: application.id }, staff, approvalKey);
  await call("onboarding.approve", { applicationId: application.id }, staff, approvalKey);
  expect(active.status).toBe("Active");
  expect(statusEmails).not.toContain("onboarding");
  await domain.processOutbox();
  expect(statusEmails).toContain("onboarding");
  expect(statusEmails.filter(status => status === "onboarding")).toHaveLength(1);
  const skillSearch = await call("application.list", { search: "MongoDB" });
  expect(skillSearch.items.map((row: any) => row.id)).toContain(application.id);
  const skillFilter = await call("application.list", { skill: "React", facets: true });
  expect(skillFilter.items.map((row: any) => row.id)).toContain(application.id);
  expect(skillFilter.counts.skills.some((row: any) => row.name === "React")).toBe(true);
  const timeline = (await call("application.get", { id: application.id }, intern)).history.map((event: any) => event.title);
  expect(timeline).toContain("Interview scheduled"); expect(timeline).toContain("Offer sent"); expect(timeline).toContain("Onboarding submitted"); expect(timeline).toContain("Intern onboarded");
  const project = await call("project.create", { project: { name: "Test project", description: "Test description", program: "Software Engineer Intern", team: [] } });
  const available = () => call("project.list", { availableFor: application.id });
  expect((await available()).items.map((row: any) => row.id)).toContain(project.id);
  const assignmentKey = key();
  await call("project.assign", { projectId: project.id, applicationId: application.id }, staff, assignmentKey);
  await call("project.assign", { projectId: project.id, applicationId: application.id }, staff, assignmentKey);
  expect((await available()).items.map((row: any) => row.id)).not.toContain(project.id);
  expect((await call("project.list", { applicationId: application.id })).items[0].team).toEqual([application.id]);
  const task = await call("task.create", { projectId: project.id, applicationId: application.id, title: "Test task", description: "Implement work", dueOn: "2026-12-01", required: true });
  await expect(call("intern.update", { id: active.id, patch: { status: "Completed" } })).rejects.toBeInstanceOf(DomainError);
  await expect(call("submission.create", { taskId: task.id, notes: "wrong owner" }, other)).rejects.toBeInstanceOf(DomainError);
  const first = await call("submission.create", { taskId: task.id, notes: "first version" }, intern);
  expect(first.version).toBe(1);
  await call("submission.review", { id: first.id, decision: "Changes requested", feedback: "Please improve it" });
  const second = await call("submission.create", { taskId: task.id, notes: "second version" }, intern);
  expect(second.version).toBe(2);
  await expect(call("submission.review", { id: first.id, decision: "Approved" })).rejects.toBeInstanceOf(DomainError);
  await call("submission.review", { id: second.id, decision: "Approved" });
  await call("intern.update", { id: active.id, patch: { status: "Completed" } });
  const certificateKey = key(); const generated = await call("certificate.generate", { internIds: [active.id] }, staff, certificateKey);
  const retry = await call("certificate.generate", { internIds: [active.id] }, staff, certificateKey);
  const again = await call("certificate.generate", { internIds: [active.id] });
  expect(generated[0].id).toBe(retry[0].id); expect(generated[0].id).toBe(again[0].id);
  // Certificate emails are queued once (not per retry) and sent by the outbox worker.
  expect(statusEmails.filter(status => status === "certificate")).toHaveLength(0);
  await domain.processOutbox();
  expect(statusEmails.filter(status => status === "certificate")).toHaveLength(1);
  expect(await domain.collection("certificates").countDocuments({ internId: active.id })).toBe(1);
  const snapshot = await call("intern.snapshot", {}, intern);
  expect(snapshot.my.intern.status).toBe("Completed"); expect(snapshot.my.certificates[0].id).toBe(generated[0].id); expect(snapshot.my.interview.id).toBe(interview.id);
  expect(statusEmails).toContain("certificate");
  expect((await call("intern.snapshot", {}, other)).my.certificates).toEqual([]);
  const event = await domain.collection("events").findOne({ type: "submission.review", applicationIds: application.id }); expect(event).toBeTruthy();
}, 120000);
